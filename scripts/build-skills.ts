/**
 * Bundles skills/<name>/SKILL.md into src/lib/skills/generated.ts, so the live routes
 * (guest replies, the assistant) load the same text the Managed Agents get through the
 * Skills API. Runs before `dev`, `build` and `test`.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..', 'skills');
const skills: Record<string, { description: string; body: string }> = {};

for (const name of readdirSync(root).sort()) {
  const file = path.join(root, name, 'SKILL.md');
  if (name.startsWith('_') || !existsSync(file)) continue;
  const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${name}/SKILL.md has no frontmatter`);
  const description = /description:\s*(.+)/.exec(match[1])?.[1].trim() ?? '';
  skills[name] = { description, body: match[2].trim() };
}

const rules = readFileSync(path.join(root, '_shared', 'RULES.md'), 'utf8').replace(/\r\n/g, '\n').trim();
const out = `// Generated by scripts/build-skills.ts from skills/. Do not edit.
export const SHARED_RULES = ${JSON.stringify(rules)};
export const SKILLS = ${JSON.stringify(skills, null, 2)} as const;
export type SkillName = keyof typeof SKILLS;
`;
writeFileSync(path.resolve(__dirname, '..', 'src', 'lib', 'skills', 'generated.ts'), out);
console.log(`skills: bundled ${Object.keys(skills).length}`);
